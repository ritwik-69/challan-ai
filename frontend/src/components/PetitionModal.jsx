import React, { useState } from 'react';
import { X, Copy, Check, Download, ExternalLink, ShieldAlert, Award, FileText, CheckCircle2, ListChecks } from 'lucide-react';
import confetti from 'canvas-confetti';

export default function PetitionModal({ challan, isOpen, onClose }) {
  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState('petition');

  if (!isOpen) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(challan.petitionDraft);
    setCopied(true);
    confetti({
      particleCount: 65,
      spread: 70,
      origin: { y: 0.6 }
    });
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownload = () => {
    const element = document.createElement('a');
    const file = new Blob([challan.petitionDraft], { type: 'text/plain;charset=utf-8' });
    element.href = URL.createObjectURL(file);
    element.download = `Petition_${challan.challanNumber}.txt`;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  const filingChecklist = [
    { step: '1', title: 'Open Indian Virtual Courts Portal', desc: 'Visit vcourts.gov.in and select your respective State Department.' },
    { step: '2', title: 'Search by Notice / Mobile Number', desc: `Enter Notice No: ${challan.challanNumber} or your registered vehicle plate ${challan.registeredVehicle.plate}.` },
    { step: '3', title: 'Select Option: "Contest Challan"', desc: 'Click "I dispute this offence / Wish to contest in Court" instead of "Pay Fine".' },
    { step: '4', title: 'Paste Generated Petition', desc: 'Copy and paste the statutory petition generated by ChallanAI into the grounds textarea.' },
    { step: '5', title: 'Attach Evidence Photos', desc: 'Upload the photographic evidence showing notice dispatch date and camera vehicle mismatch.' },
  ];

  return (
    <div style={{
      position: 'fixed',
      top: 0,
      left: 0,
      width: '100vw',
      height: '100vh',
      backgroundColor: 'rgba(0, 0, 0, 0.85)',
      backdropFilter: 'blur(10px)',
      display: 'flex',
      alignItems: 'center',
      justifyContent: 'center',
      zIndex: 9999,
      padding: '20px'
    }}>
      <div className="glass-panel" style={{
        width: '100%',
        maxWidth: '820px',
        maxHeight: '92vh',
        display: 'flex',
        flexDirection: 'column',
        borderRadius: 'var(--radius-xl)',
        background: '#090d16',
        border: '1px solid rgba(245, 158, 11, 0.35)',
        boxShadow: '0 25px 50px -12px rgba(0, 0, 0, 0.8), 0 0 45px rgba(245, 158, 11, 0.18)',
        overflow: 'hidden'
      }}>
        {/* Modal Top Bar */}
        <div style={{
          display: 'flex',
          justifyContent: 'space-between',
          alignItems: 'center',
          padding: '18px 24px',
          borderBottom: '1px solid var(--border-subtle)',
          background: 'rgba(255, 255, 255, 0.02)'
        }}>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <h3 style={{ fontSize: '1.25rem', margin: 0, fontWeight: 700 }}>
                Formal Virtual Court Dispute Petition
              </h3>
              <span className="badge badge-success" style={{ fontSize: '0.68rem' }}>
                <Award size={12} /> Ready for Direct Filing
              </span>
            </div>
            <p style={{ margin: '2px 0 0', fontSize: '0.8rem', color: 'var(--text-muted)' }}>
              Jurisdiction: {challan.courtName} • Citation: {challan.challanNumber}
            </p>
          </div>

          <button
            id="btn-close-modal"
            onClick={onClose}
            style={{
              background: 'rgba(255, 255, 255, 0.08)',
              border: 'none',
              color: 'var(--text-muted)',
              width: '34px',
              height: '34px',
              borderRadius: '50%',
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'center',
              cursor: 'pointer'
            }}
          >
            <X size={18} />
          </button>
        </div>

        {/* Tab Switcher */}
        <div style={{
          display: 'flex',
          gap: '8px',
          padding: '12px 24px',
          borderBottom: '1px solid var(--border-subtle)',
          background: 'rgba(0,0,0,0.2)'
        }}>
          <button
            onClick={() => setActiveTab('petition')}
            style={{
              background: activeTab === 'petition' ? 'rgba(245, 158, 11, 0.15)' : 'transparent',
              border: activeTab === 'petition' ? '1px solid rgba(245, 158, 11, 0.4)' : '1px solid transparent',
              color: activeTab === 'petition' ? '#fbbf24' : 'var(--text-muted)',
              padding: '6px 14px',
              borderRadius: '6px',
              fontSize: '0.8rem',
              fontWeight: 600,
              display: 'flex',
              alignItems: 'center',
              gap: '6px'
            }}
          >
            <FileText size={14} />
            <span>Statutory Petition Text</span>
          </button>

          <button
            onClick={() => setActiveTab('checklist')}
            style={{
              background: activeTab === 'checklist' ? 'rgba(16, 185, 129, 0.15)' : 'transparent',
              border: activeTab === 'checklist' ? '1px solid rgba(16, 185, 129, 0.4)' : '1px solid transparent',
              color: activeTab === 'checklist' ? '#34d399' : 'var(--text-muted)',
              padding: '6px 14px',
              borderRadius: '6px',
              fontSize: '0.8rem',
              fontWeight: 600,
              display: 'flex',
              alignItems: 'center',
              gap: '6px'
            }}
          >
            <ListChecks size={14} />
            <span>Step-by-Step Filing Guide (vcourts.gov.in)</span>
          </button>
        </div>

        {/* Modal Scrollable Body */}
        <div style={{
          padding: '24px',
          overflowY: 'auto',
          flex: 1
        }}>
          {activeTab === 'petition' ? (
            <div>
              <div style={{
                background: 'rgba(245, 158, 11, 0.08)',
                border: '1px solid rgba(245, 158, 11, 0.25)',
                borderRadius: 'var(--radius-sm)',
                padding: '12px 16px',
                marginBottom: '16px',
                fontSize: '0.8rem',
                color: '#fbbf24',
                display: 'flex',
                alignItems: 'center',
                gap: '10px'
              }}>
                <ShieldAlert size={18} style={{ flexShrink: 0 }} />
                <span>
                  This formal petition complies with Section 208 MV Act and Central Motor Vehicle Rules. Copy it and submit it directly to the Virtual Traffic Court portal without paying legal fees.
                </span>
              </div>

              <pre style={{
                background: '#04060a',
                border: '1px solid var(--border-subtle)',
                borderRadius: 'var(--radius-sm)',
                padding: '20px',
                color: '#e2e8f0',
                fontFamily: 'var(--font-mono)',
                fontSize: '0.82rem',
                lineHeight: 1.6,
                whiteSpace: 'pre-wrap',
                margin: 0,
                maxHeight: '400px',
                overflowY: 'auto'
              }}>
                {challan.petitionDraft}
              </pre>
            </div>
          ) : (
            <div style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
              <div style={{ fontSize: '0.82rem', color: 'var(--text-muted)', marginBottom: '4px' }}>
                Follow this simple 5-step process to submit your petition to the Indian Virtual Traffic Court portal:
              </div>

              {filingChecklist.map((item) => (
                <div
                  key={item.step}
                  style={{
                    display: 'flex',
                    alignItems: 'flex-start',
                    gap: '14px',
                    background: 'rgba(255, 255, 255, 0.025)',
                    border: '1px solid var(--border-subtle)',
                    padding: '14px 16px',
                    borderRadius: '8px'
                  }}
                >
                  <div style={{
                    width: '28px',
                    height: '28px',
                    borderRadius: '50%',
                    background: 'rgba(16, 185, 129, 0.2)',
                    color: '#34d399',
                    fontSize: '0.82rem',
                    fontWeight: 800,
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'center',
                    flexShrink: 0
                  }}>
                    {item.step}
                  </div>
                  <div>
                    <div style={{ fontWeight: 700, color: '#fff', fontSize: '0.88rem', marginBottom: '2px' }}>
                      {item.title}
                    </div>
                    <div style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>
                      {item.desc}
                    </div>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>

        {/* Modal Bottom Actions */}
        <div style={{
          display: 'flex',
          justifyContent: 'space-between',
          alignItems: 'center',
          padding: '18px 24px',
          borderTop: '1px solid var(--border-subtle)',
          background: 'rgba(255, 255, 255, 0.02)',
          flexWrap: 'wrap',
          gap: '12px'
        }}>
          <a
            href="https://vcourts.gov.in"
            target="_blank"
            rel="noopener noreferrer"
            className="btn-secondary"
            style={{ fontSize: '0.82rem', padding: '9px 14px' }}
          >
            <ExternalLink size={14} />
            <span>Open eCourts vcourts.gov.in</span>
          </a>

          <div style={{ display: 'flex', gap: '10px' }}>
            <button
              onClick={handleDownload}
              className="btn-secondary"
              style={{ fontSize: '0.82rem', padding: '9px 14px' }}
            >
              <Download size={14} />
              <span>Download (.txt)</span>
            </button>

            <button
              id="btn-copy-petition"
              onClick={handleCopy}
              className="btn-primary"
              style={{ fontSize: '0.82rem', padding: '9px 20px' }}
            >
              {copied ? <Check size={16} /> : <Copy size={16} />}
              <span>{copied ? 'Copied to Clipboard! 🎉' : 'Copy Legal Petition'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
